// TALI translations — English is the key, Arabic is the value.
// t('Save order') → 'حفظ الطلب' when the app language is Arabic.
// Strings with variables use {name} placeholders: t('Step {n} of 3', { n: 2 }).

export type Lang = 'en' | 'ar'

let current: Lang = 'en'
export const setCurrentLang = (l: Lang) => {
  current = l
}
export const getLang = () => current
export const isRTL = () => current === 'ar'

type Vars = Record<string, string | number>

const fill = (s: string, vars?: Vars) =>
  vars ? Object.entries(vars).reduce((out, [k, v]) => out.split(`{${k}}`).join(String(v)), s) : s

// Patterns for text that is built from data (order numbers, names …)
const rules: [RegExp, string | ((m: RegExpMatchArray) => string)][] = [
  [/^Restock: (.+)$/, (m) => `إعادة تعبئة: ${ar[m[1]] ?? m[1]}`],
  [/^Deliver #(\S+)$/, 'توصيل #$1'],
  [/^Pack order #(\S+)$/, 'تجهيز الطلب #$1'],
  [/^Deliver #(\S+) to Omar$/, 'توصيل #$1 لعمر'],
  [/^Linked to #(\S+)$/, 'مرتبطة بالطلب #$1'],
  [/^(\d+) Nov$/, '$1 نوفمبر'],
  // real dates and times
  [/^(\d{1,2}:\d{2}) (AM|PM)$/, (m) => `${m[1]} ${m[2] === 'AM' ? 'ص' : 'م'}`],
  [/^(\d{1,2}) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)$/, (m) => `${m[1]} ${arMonths[m[2]]}`],
  [/^(Today|Tomorrow|Yesterday|\d{1,2} \w{3}) · (\d{1,2}:\d{2} [AP]M)$/, (m) => `${t(m[1])} · ${t(m[2])}`],
  [/^Done at (\d{1,2}:\d{2} [AP]M)$/, (m) => `أُنجزت ${t(m[1])}`],
]

const arMonths: Record<string, string> = {
  Jan: 'يناير', Feb: 'فبراير', Mar: 'مارس', Apr: 'أبريل', May: 'مايو', Jun: 'يونيو',
  Jul: 'يوليو', Aug: 'أغسطس', Sep: 'سبتمبر', Oct: 'أكتوبر', Nov: 'نوفمبر', Dec: 'ديسمبر',
}

export function t(s: string, vars?: Vars): string {
  if (current === 'en') return fill(s, vars)
  const hit = ar[s]
  if (hit !== undefined) return fill(hit, vars)
  for (const [re, rep] of rules) {
    const m = s.match(re)
    if (m) return fill(typeof rep === 'string' ? s.replace(re, rep) : rep(m), vars)
  }
  return fill(s, vars)
}

/** Translate a "A · B · C" string piece by piece. */
export const tParts = (s: string) => s.split(' · ').map((p) => t(p)).join(' · ')

